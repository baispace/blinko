"""Flatten the bundled WenKai CSS without duplicating or modifying font binaries."""
from pathlib import Path

root = Path(__file__).resolve().parent.parent
base = root / 'app/public/font-assets/lxgw-wenkai/1.7.0'
css = '/* LXGW WenKai 1.7.0: flattened startup stylesheet, OFL.txt. Generated by scripts/build-wenkai-startup.py. */\n'
for weight in ('regular', 'bold'):
    css += (base / f'lxgwwenkai-{weight}.css').read_text() + '\n'
(base / 'startup-v2.css').write_text(css)
